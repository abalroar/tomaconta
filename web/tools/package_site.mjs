import {cp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const target=process.argv[2];if(!target)throw Error('Informe o checkout isolado do site pessoal.');
await mkdir(resolve(target,'public/atlas-sfn'),{recursive:true});
await cp(resolve(root,'dist'),resolve(target,'public/atlas-sfn'),{recursive:true});
await mkdir(resolve(target,'public/tomaconta'),{recursive:true});
await writeFile(resolve(target,'public/tomaconta/index.html'),'<!doctype html><html lang="pt-BR"><head><meta charset="utf-8"><title>Atlas SFN</title><meta http-equiv="refresh" content="0;url=/atlas-sfn/"><script>location.replace("/atlas-sfn/"+location.search+location.hash)</script></head><body><a href="/atlas-sfn/">Atlas SFN</a></body></html>');
await cp(resolve(root,'server/bcb.js'),resolve(target,'worker/tomaconta.js'));
await cp(resolve(root,'server/shared.js'),resolve(target,'worker/tomaconta-shared.js'));
await cp(resolve(root,'server/shared-schema.js'),resolve(target,'worker/shared-schema.js'));
const manifest=JSON.parse(await readFile(resolve(root,'public/data/manifest.json'),'utf8'));
const frontendCommit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
await writeFile(resolve(target,'public/atlas-sfn/build.json'),JSON.stringify({app:'Atlas SFN',version:3,sourceData:manifest.sourceCommit,builtAt:manifest.builtAt,frontendCommit,frontendBuiltAt:new Date().toISOString(),charts:manifest.chartCount}));
console.log('Atlas SFN copiado para public/atlas-sfn com os handlers BCB e compartilhado; a entrada antiga redireciona ao novo endereço.');
